#ifndef SM8750_ADRENO_RESOURCES_H
#define SM8750_ADRENO_RESOURCES_H

/* Register apertures from the SM8750P Linux handoff. The GMU register XML
 * uses GPU-relative dword indices, including for registers beyond the GPU
 * node's own MMIO aperture. Convert them to offsets within the GMU mapping. */
#define SM8750_ADRENO_GPU_BASE          0x03d00000U
#define SM8750_ADRENO_GMU_BASE          0x03d37000U
#define SM8750_ADRENO_GMU_BYTES         0x00068000U
#define SM8750_ADRENO_GMU_OFFSET(word)  (4U * (word) - (SM8750_ADRENO_GMU_BASE - SM8750_ADRENO_GPU_BASE))
#define SM8750_ADRENO_GMU_ITCM          SM8750_ADRENO_GMU_OFFSET(0x1b400U)
#define SM8750_ADRENO_GMU_DTCM          SM8750_ADRENO_GMU_OFFSET(0x1c400U)
#define SM8750_ADRENO_GMU_CORE_VERSION  SM8750_ADRENO_GMU_OFFSET(0x1d3f8U)
#define SM8750_ADRENO_GMU_ICACHE_CONFIG SM8750_ADRENO_GMU_OFFSET(0x1f400U)
#define SM8750_ADRENO_GMU_DCACHE_CONFIG SM8750_ADRENO_GMU_OFFSET(0x1f401U)
#define SM8750_ADRENO_GMU_SYS_BUS_CONFIG SM8750_ADRENO_GMU_OFFSET(0x1f40fU)
#define SM8750_ADRENO_GMU_GBIF_QOS      SM8750_ADRENO_GMU_OFFSET(0x1f50bU)
#define SM8750_ADRENO_GMU_CM3_SYSRESET  SM8750_ADRENO_GMU_OFFSET(0x1f800U)
#define SM8750_ADRENO_GMU_BOOT_CONFIG   SM8750_ADRENO_GMU_OFFSET(0x1f801U)
#define SM8750_ADRENO_GMU_FW_INIT       SM8750_ADRENO_GMU_OFFSET(0x1f81cU)
#define SM8750_ADRENO_GMU_CM3_CONFIG    SM8750_ADRENO_GMU_OFFSET(0x1f82dU)
#define SM8750_ADRENO_GMU_COUNTER_LOW   SM8750_ADRENO_GMU_OFFSET(0x1f840U)
#define SM8750_ADRENO_GMU_COUNTER_HIGH  SM8750_ADRENO_GMU_OFFSET(0x1f841U)
#define SM8750_ADRENO_GMU_HFI_STATUS    SM8750_ADRENO_GMU_OFFSET(0x1f980U)
#define SM8750_ADRENO_GMU_HFI_INFO      SM8750_ADRENO_GMU_OFFSET(0x1f984U)
#define SM8750_ADRENO_GMU_HFI_TABLE     SM8750_ADRENO_GMU_OFFSET(0x1f985U)
#define SM8750_ADRENO_GMU_HFI_INIT      SM8750_ADRENO_GMU_OFFSET(0x1f986U)
#define SM8750_ADRENO_GMU_GMU2HOST      SM8750_ADRENO_GMU_OFFSET(0x1f992U)
#define SM8750_ADRENO_GMU_HOST2GMU      SM8750_ADRENO_GMU_OFFSET(0x1f994U)
#define SM8750_ADRENO_GMU_LOG_CONFIG    SM8750_ADRENO_GMU_OFFSET(0x1f9c8U)
#define SM8750_ADRENO_GMU_LOG_INDEX     SM8750_ADRENO_GMU_OFFSET(0x1f9c9U)
#define SM8750_ADRENO_GMU_CHIP_ID       SM8750_ADRENO_GMU_OFFSET(0x1f9caU)
#define SM8750_ADRENO_GMU_AO_IRQ        SM8750_ADRENO_GMU_OFFSET(0x23b05U)
#define SM8750_ADRENO_GMU_FENCE_RANGE   SM8750_ADRENO_GMU_OFFSET(0x23b11U)
#define SM8750_ADRENO_GMU_CM3_FAULT     (1U << 23)
#define SM8750_ADRENO_GMU_AO_FAULTS     ((1U << 5) | (1U << 3) | 1U)

/* GBIF register offsets relative to the GPU aperture. */
#define SM8750_ADRENO_GBIF_CX_CONFIG    0xf000U
#define SM8750_ADRENO_GBIF_QSB_SIDE0    0xf00cU
#define SM8750_ADRENO_GBIF_QSB_SIDE1    0xf010U
#define SM8750_ADRENO_GBIF_QSB_SIDE2    0xf014U
#define SM8750_ADRENO_GBIF_QSB_SIDE3    0xf018U

/* CM3 firmware address space. TCM is accessible through MMIO. The other
 * firmware windows require a GMU SMMU mapping and CPU-accessible backing. */
#define SM8750_GMU_ITCM_ADDRESS         0x00000000U
#define SM8750_GMU_DTCM_ADDRESS         0x10004000U
#define SM8750_GMU_TCM_BYTES            0x00004000U
#define SM8750_GMU_ICACHE_IOVA          0x00004000U
#define SM8750_GMU_ICACHE_BYTES         0x00ffc000U
#define SM8750_GMU_SCRATCH_IOVA         0x60000000U
#define SM8750_GMU_SCRATCH_BYTES        0x00004000U
#define SM8750_GMU_DEBUG_IOVA           0x60400000U
#define SM8750_GMU_DEBUG_BYTES          0x00007000U
#define SM8750_GMU_LOG_BYTES            0x00004000U
#define SM8750_GMU_HFI_BYTES            0x00004000U
#define SM8750_GMU_LOG_IOVA             (SM8750_GMU_SCRATCH_IOVA + SM8750_GMU_SCRATCH_BYTES)
#define SM8750_GMU_HFI_IOVA             (SM8750_GMU_LOG_IOVA + SM8750_GMU_LOG_BYTES)
#define SM8750_GMU_PAGE_BYTES           0x00001000U
#define SM8750_GPU_SMMU_BASE            0x03da0000U
#define SM8750_GPU_SMMU_BYTES           0x00040000U
#define SM8750_GMU_STREAM_ID            5U

/* GPUCC CX register page. Offsets are relative to this page. */
#define SM8750_GPUCC_BASE               0x03d90000U
#define SM8750_GPUCC_MAP_BYTES          0x0000a000U
#define SM8750_GPUCC_CX_PAGE_OFFSET     0x9000U
#define SM8750_GPUCC_CX_PAGE            (SM8750_GPUCC_BASE + SM8750_GPUCC_CX_PAGE_OFFSET)
#define SM8750_GPUCC_CX_GDSCR           0x080U
#define SM8750_GPUCC_CX_GDS_HW_CTRL      0x094U
#define SM8750_GPUCC_AHB_CBCR           0x0bcU
#define SM8750_GPUCC_CX_GMU_CBCR        0x0d4U
#define SM8750_GPUCC_CXO_CBCR           0x0e4U
#define SM8750_GPUCC_HUB_CX_INT_CBCR     0x0e8U

#define SM8750_GCC_GPU_MAP_BYTES        0x00072000U
#define SM8750_GCC_GPU_VOTE_REG         0x52000U

/* AP RPMh RSC DRV-2. The Elden Linux DT selects DRV-2 and assigns the
 * first three TCSes to active requests. The other TCSes are for sleep/wake. */
#define SM8750_APPS_RSC_DRV2_BASE       0x16520000U
#define SM8750_APPS_RSC_DRV2_PROBE_SIZE 0x00002000U
#define SM8750_APPS_RSC_TCS_BASE        0x0d00U
#define SM8750_APPS_RSC_TCS_STRIDE      0x02a0U
#define SM8750_APPS_RSC_ACTIVE_TCS      3U

#endif
